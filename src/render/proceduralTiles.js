import { mb32 } from "../core/rng.js";
import { spr, R, spk, blob } from "./spriteUtils.js";

export function createTiles() {
  const TI = {},
    r = mb32(99);
  TI[0] = spr(16, 16, (g) => {
    spk(g, "#2a3322", 24, ["#242d1e", "#313b27", "#37422b"], r);
    for (let i = 0; i < 3; i++)
      R(g, Math.floor(r() * 16), Math.floor(r() * 14), 1, 2, "#3c4a2c");
  });
  TI[1] = spr(16, 16, (g) => spk(g, "#4a3b2a", 22, ["#3e3122", "#554430"], r));
  TI[2] = spr(16, 16, (g) => {
    spk(g, "#30312c", 16, ["#282924", "#383934"], r);
    if (r() < 0.4) R(g, (r() * 12) | 0, (r() * 14) | 0, 4, 1, "#24251f");
  });
  TI[3] = spr(16, 16, (g) => {
    spk(g, "#55574f", 12, ["#4b4d45", "#5e6057"], r);
    R(g, 0, 0, 16, 1, "#66685f");
    R(g, 0, 15, 16, 1, "#3f413a");
  });
  TI[4] = spr(16, 16, (g) => {
    spk(g, "#6b5638", 10, ["#5f4c31", "#75603f"], r);
    for (let y = 3; y < 16; y += 4) R(g, 0, y, 16, 1, "#54432b");
  });
  TI[5] = spr(16, 16, (g) => {
    R(g, 0, 0, 16, 16, "#8b8f86");
    R(g, 0, 0, 8, 8, "#7e827a");
    R(g, 8, 8, 8, 8, "#7e827a");
  });
  TI[6] = spr(16, 16, (g) => {
    R(g, 0, 0, 16, 16, "#4c3322");
    for (let y = 0; y < 16; y += 4) {
      const o = (y / 4) % 2 ? 4 : 0;
      for (let x = -4; x < 16; x += 8) {
        R(g, x + o, y, 7, 3, "#6e4a33");
        R(g, x + o, y, 7, 1, "#7d5740");
      }
    }
  });
  TI[7] = spr(16, 16, (g) => {
    R(g, 0, 0, 16, 16, "#5d646b");
    for (let x = 0; x < 16; x += 5) R(g, x, 0, 1, 16, "#4a5057");
    R(g, 0, 0, 16, 1, "#6d747b");
  });
  TI[8] = spr(16, 16, (g) => {
    g.drawImage(TI[6], 0, 0);
    R(g, 3, 3, 10, 10, "#22323c");
    R(g, 4, 4, 8, 8, "#31485a");
    R(g, 4, 4, 3, 2, "#7fb8d8");
    R(g, 7, 3, 2, 10, "#4c3322");
    R(g, 3, 7, 10, 2, "#4c3322");
  });
  TI[9] = spr(16, 16, (g) => spk(g, "#565a52", 14, ["#4c5048", "#5e625a"], r));
  TI[10] = spr(16, 16, (g) => {
    spk(g, "#3f5219", 18, ["#33421a", "#5c7a1e"], r);
    R(g, (r() * 14) | 0, (r() * 14) | 0, 1, 1, "#a6e83c");
  });
  TI[11] = spr(16, 16, (g) => spk(g, "#2c2f24", 20, ["#23261c", "#3a3d30"], r));
  TI[12] = spr(16, 16, (g) => spk(g, "#4c5340", 12, ["#434a38", "#555c48"], r));
  TI[13] = spr(16, 16, (g) => {
    spk(g, "#3d4034", 16, ["#33362b", "#484b3d"], r);
    for (let i = 0; i < 3; i++)
      R(g, (r() * 13) | 0, (r() * 13) | 0, 3, 2, "#565a4c");
  });
  TI[14] = spr(16, 16, (g) => {
    g.drawImage(TI[0], 0, 0);
    R(g, 3, 13, 10, 2, "rgba(0,0,0,.3)");
    R(g, 7, 9, 3, 6, "#4a3524");
    blob(g, 8, 6, [6, 10, 13, 14, 13, 10, 7], "#3c4a2a", "#46562f");
  });
  TI[15] = spr(16, 16, (g) => {
    g.drawImage(TI[0], 0, 0);
    blob(g, 8, 9, [6, 10, 12, 12, 9], "#5a5e55", "#6a6e64");
  });
  TI[16] = spr(16, 16, (g) => {
    g.drawImage(TI[0], 0, 0);
    for (let x = 1; x < 16; x += 4) {
      R(g, x, 3, 3, 11, "#6b5638");
      R(g, x, 3, 3, 2, "#8a7450");
    }
    R(g, 0, 7, 16, 2, "#54432b");
  });
  TI[17] = spr(16, 16, (g) => {
    g.drawImage(TI[0], 0, 0);
    blob(g, 8, 10, [6, 10, 12, 10, 6], "#37452a", "#42522f");
  });
  TI[18] = spr(16, 16, (g) => {
    spk(g, "#1e3a4a", 10, ["#24465a", "#1a3240"], r);
    R(g, (r() * 10) | 0, (r() * 14) | 0, 5, 1, "#3a6a8a");
  });
  TI[19] = spr(16, 16, (g) => spk(g, "#7a3a2a", 8, ["#8a4a34", "#6a3024"], r));
  TI[20] = spr(16, 16, (g) => {
    g.drawImage(TI[2], 0, 0);
    R(g, 0, 0, 16, 16, "rgba(0,0,0,.12)");
    R(g, 2, 2, 12, 1, "#6a6a5a");
    R(g, 2, 13, 12, 1, "#6a6a5a");
  });
  TI[21] = spr(16, 16, (g) => {
    g.drawImage(TI[0], 0, 0);
    for (let y = 2; y < 16; y += 5) {
      R(g, 0, y, 16, 1, "#3a2f22");
      R(g, 3, y - 1, 2, 2, "#6f9c22");
      R(g, 11, y - 1, 2, 2, "#7dd87a");
    }
  });
  TI[22] = spr(16, 16, (g) => {
    g.drawImage(TI[6], 0, 0);
    R(g, 2, 2, 12, 12, "#31485a");
    R(g, 3, 3, 10, 10, "#7fb8d8");
    R(g, 4, 4, 4, 3, "#9fcce8");
  });
  TI[23] = spr(16, 16, (g) => {
    g.drawImage(TI[0], 0, 0);
    R(g, 2, 10, 12, 4, "#5c4a32");
    R(g, 2, 10, 12, 1, "#7d6644");
    R(g, 3, 14, 2, 2, "#3a2f20");
    R(g, 11, 14, 2, 2, "#3a2f20");
  });
  TI[24] = spr(16, 16, (g) => spk(g, "#6a5a48", 10, ["#5e5040", "#756450"], r));
  TI[25] = spr(16, 16, (g) => {
    R(g, 0, 0, 16, 16, "#7a3a2a");
    R(g, 2, 2, 12, 12, "#8a4a34");
    R(g, 4, 4, 8, 8, "#a86444");
  });
  TI[26] = spr(16, 16, (g) => {
    g.drawImage(TI[5], 0, 0);
    R(g, 0, 0, 16, 1, "rgba(255,255,255,.1)");
  });
  TI[27] = spr(16, 16, (g) => {
    g.drawImage(TI[2], 0, 0);
    R(g, 0, 7, 16, 2, "#b7a23c");
  });
  TI[28] = spr(16, 16, (g) => {
    g.drawImage(TI[2], 0, 0);
    R(g, 7, 0, 2, 16, "#b7a23c");
  });
  TI[29] = spr(16, 16, (g) => {
    g.drawImage(TI[2], 0, 0);
    for (let i = 0; i < 4; i++) R(g, 1 + i * 4, 2, 2, 12, "#d9cba6");
  });
  TI[30] = spr(16, 16, (g) => {
    g.drawImage(TI[0], 0, 0);
    R(g, 2, 8, 12, 6, "#4a3b2a");
    R(g, 3, 6, 3, 3, "#6f9c22");
    R(g, 9, 6, 3, 3, "#a6e83c");
  });
  TI[31] = spr(16, 16, (g) => {
    g.drawImage(TI[9], 0, 0);
    R(g, 2, 2, 12, 12, "#3a4030");
    R(g, 4, 4, 8, 8, "#565e48");
  });
  TI[32] = spr(16, 16, (g) => {
    g.drawImage(TI[2], 0, 0);
    for (let i = 0; i < 4; i++) R(g, 2, 1 + i * 4, 12, 2, "#d9cba6");
  });
  return TI;
}
